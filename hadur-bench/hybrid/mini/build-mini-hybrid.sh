#!/usr/bin/env bash
# Build the bench-only MiniRumble hybrid reference robots (../README.md). The donors' code is
# FoilistMC 1.0 (Sheldor, RWPCL) and CunobelinDC 1.2 (Skilgannon), taken unchanged from their
# rumble jars at build time, and JayLexi from this checkout. Nothing of the donors is committed.
#
#   hadur-bench/hybrid/mini/build-mini-hybrid.sh [--out DIR]
#
# Writes DIR/hybridmini.<Class>_1.0.jar for every line of hybrids.txt (default DIR:
# hadur-bench/kitlab/jars). Never release, upload or enter these in a rumble.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
OUT="$ROOT/hadur-bench/kitlab/jars"
OPP="$ROOT/hadur-bench/opponents"
VERSION=1.0
while [ $# -gt 0 ]; do
    case "$1" in
        --out) OUT="$2"; shift 2 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

API=$(find "$HOME/.m2/repository/net/sf/robocode" -name 'robocode.api-1.12.0.jar' | head -1)
[ -n "$API" ] || { echo "robocode.api 1.12.0 not in ~/.m2: run mvn package once" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/src" "$WORK/classes"

mkdir -p "$OPP"
for J in sheldor.mini.FoilistMC_1.0 jk.mini.CunobelinDC_1.2; do
    [ -f "$OPP/$J.jar" ] || curl -fsSL -o "$OPP/$J.jar" "https://robocode-archive.strangeautomata.com/robots/$J.jar"
    (cd "$WORK/src" && unzip -qo "$OPP/$J.jar" '*.java')
done
mkdir -p "$WORK/src/hadur117/mini"
cp "$ROOT/jaylexi/src/main/java/hadur117/mini/JayLexi.java" "$WORK/src/hadur117/mini/"

# One wrapper per donor: its once-a-round set-up, minus any blocking loop.
part() { # fq setup-body
    local fq=$1 setup=$2 pkg=${1%.*} cls=${1##*.}
    sed -e "s/@PKG@/$pkg/g" -e "s/@CLS@/$cls/g" "$HERE/part-template.java" \
        | python3 -c 'import sys; print(sys.stdin.read().replace("@SETUP@", sys.argv[1]), end="")' "$setup" \
        > "$WORK/src/${pkg//.//}/${cls}Part.java"
}
part sheldor.mini.FoilistMC '        super.run();'
part jk.mini.CunobelinDC '        // set up in its constructor'
part hadur117.mini.JayLexi '        waves = new java.util.ArrayList<Wave>();
        bot = this;'

cp -r "$HERE/src/." "$WORK/src/"
grep -v '^#' "$HERE/hybrids.txt" | while IFS='|' read -r CLS MOVE GUN; do
    CLS=$(echo $CLS); MOVE=$(echo $MOVE); GUN=$(echo $GUN)
    if [ "$GUN" = "-" ]; then
        PARTS="new ${MOVE}Part(this, true, true)"
        DESC="control: ${MOVE##*.} alone, through the hybrid wrapper"
    else
        PARTS="new ${MOVE}Part(this, true, false), new ${GUN}Part(this, false, true)"
        DESC="${MOVE##*.} movement with ${GUN##*.} gun"
    fi
    cat > "$WORK/src/hybridmini/$CLS.java" <<EOF
package hybridmini;

/** Bench-only MiniRumble reference: $DESC. Generated by build-mini-hybrid.sh. */
public class $CLS extends MiniHybrid {
    @Override
    protected robocode.AdvancedRobot[] makeParts() {
        return new robocode.AdvancedRobot[] {$PARTS};
    }
}
EOF
    echo "$CLS|$DESC" >> "$WORK/list.txt"
done

find "$WORK/src" -name '*.java' > "$WORK/sources.txt"
JAVAC_OK=0
javac -nowarn --release 8 -encoding UTF-8 -cp "$API" -d "$WORK/classes" @"$WORK/sources.txt" > "$WORK/javac.log" 2>&1 || JAVAC_OK=$?
grep -v -e '^Note:' -e 'warning: \[options\]' -e '^1 warning' "$WORK/javac.log" || true
[ "$JAVAC_OK" -eq 0 ] || { echo "javac failed" >&2; exit 1; }

mkdir -p "$OUT"
while IFS='|' read -r CLS DESC; do
    [ -f "$WORK/classes/hybridmini/$CLS.class" ] || { echo "compile failed: $CLS" >&2; exit 1; }
    STAGE="$WORK/jar-$CLS"
    cp -r "$WORK/classes" "$STAGE"
    cat > "$STAGE/hybridmini/$CLS.properties" <<EOF
#Robocode Robot Properties
robot.description=Bench-only reference, never for the rumble: $DESC. Code credits in hadur-bench/hybrid/README.md (FoilistMC by Sheldor, RWPCL; CunobelinDC by Skilgannon).
robot.author.name=lgriffin
robot.classname=hybridmini.$CLS
robot.version=$VERSION
robocode.version=1.9.3.0
EOF
    cp "$HERE/../README.md" "$STAGE/hybridmini/README.md"
    JAR="$OUT/hybridmini.${CLS}_${VERSION}.jar"
    rm -f "$JAR"
    (cd "$STAGE" && jar cf "$JAR" .)
    echo "built $JAR"
done < "$WORK/list.txt"
